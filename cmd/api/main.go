// listEntities godoc
// @Summary      Entity taxonomy, or entities of a type
// @Description  Without type=: the taxonomy (each entity_type + count) for category discovery. With type=<t>: entities of that type, using the same filters/paging as /v1/places.
// @Tags         entities
// @Produce      json
// @Param        type          query string  false "entity_type to list; omit for the taxonomy"
// @Param        q             query string  false "fuzzy name search"
// @Param        min_sources   query int     false "min distinct sources"
// @Param        min_platforms query int     false "min distinct platforms"
// @Param        fresh_only    query boolean false "drop stale volatile places"
// @Param        near          query string  false "lat,lng for radius search"
// @Param        radius_km     query number  false "radius (km) for near="
// @Param        bbox          query string  false "minLng,minLat,maxLng,maxLat"
// @Param        sort          query string  false "trust | freshness"
// @Param        limit         query int     false "page size (<=100)"
// @Param        offset        query int     false "page offset"
// @Param        cursor        query string  false "keyset cursor from a previous response's next_cursor (default ordering only)"
// @Success      200 {object} httpx.Envelope
// @Router       /v1/entities [get]
func (a *api) listEntities(w http.ResponseWriter, req *http.Request) {
	q := req.URL.Query()
	typ := q.Get("type")
	if typ == "" {
		types, err := a.db.ListEntityTypes(req.Context())
		if err != nil {
			log.Printf("entity types: %v", err)
			httpx.Error(w, http.StatusInternalServerError, "internal", "could not load entity types")
			return
		}
		httpx.JSON(w, http.StatusOK, types, map[string]any{"count": len(types)})
		return
	}
	// ?type=... -> reuse the places query, pinned to this entity_type.
	limit := clampInt(atoiOr(q.Get("limit"), 20), 1, 100)
	offset := maxInt(atoiOr(q.Get("offset"), 0), 0)
	eparams := store.PlacesParams{
		EntityType:   typ,
		City:         q.Get("city"),
		Country:      q.Get("country"),
		Category:     q.Get("category"),
		Q:            q.Get("q"),
		MinSources:   atoiOr(q.Get("min_sources"), 0),
		MinPlatforms: atoiOr(q.Get("min_platforms"), 0),
		MaxSourceAge: maxSourceAge(q),
		FreshOnly:    q.Get("fresh_only") == "true",
		Sort:         q.Get("sort"),
		Cursor:       q.Get("cursor"),
		Limit:        limit,
		Offset:       offset,
	}
	applyGeo(q, &eparams)
	places, next, err := a.db.ListPlaces(req.Context(), eparams)
	if err != nil {
		log.Printf("entities type=%q: %v", typ, err)
		httpx.Error(w, http.StatusInternalServerError, "internal", "could not load entities")
		return
	}
	meta := map[string]any{"type": typ, "count": len(places), "limit": limit, "offset": offset}
	if next != "" {
		meta["next_cursor"] = next
	}
	httpx.JSON(w, http.StatusOK, places, meta)
}

// atoiOr parses s as an int, falling back to def on empty/invalid input — so a
// missing or junk ?limit= never errors the request, it just uses the default.
func atoiOr(s string, def int) int {
	if n, err := strconv.Atoi(s); err == nil {
		return n
	}
	return def
}

func clampInt(n, lo, hi int) int {
	if n < lo {
		return lo
	}
	if n > hi {
		return hi
	}
	return n
}

func maxInt(a, b int) int {
	if a > b {
		return a
	}
	return b
}

// maxSourceAge reads the explicit max_source_age_days filter (0 = no filter).
// fresh_only is handled separately (band-aware) via PlacesParams.FreshOnly.
func maxSourceAge(q url.Values) int {
	return maxInt(atoiOr(q.Get("max_source_age_days"), 0), 0)
}

// applyGeo parses the geo query params onto p. near="lat,lng" (+ optional
// radius_km) enables radius search; bbox="minLng,minLat,maxLng,maxLat" filters to
// a map viewport. Malformed values are ignored (the filter just doesn't apply).
func applyGeo(q url.Values, p *store.PlacesParams) {
	if n := q.Get("near"); n != "" {
		parts := strings.Split(n, ",")
		if len(parts) == 2 {
			lat, e1 := strconv.ParseFloat(strings.TrimSpace(parts[0]), 64)
			lng, e2 := strconv.ParseFloat(strings.TrimSpace(parts[1]), 64)
			if e1 == nil && e2 == nil {
				p.HasNear, p.NearLat, p.NearLng = true, lat, lng
				if r, err := strconv.ParseFloat(q.Get("radius_km"), 64); err == nil {
					p.RadiusKm = r
				}
			}
		}
	}
	if b := q.Get("bbox"); b != "" {
		parts := strings.Split(b, ",")
		if len(parts) == 4 {
			var f [4]float64
			ok := true
			for i, s := range parts {
				v, err := strconv.ParseFloat(strings.TrimSpace(s), 64)
				if err != nil {
					ok = false
					break
				}
				f[i] = v
			}
			if ok {
				p.HasBBox, p.BBox = true, f
			}
		}
	}
}
