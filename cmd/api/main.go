// Command api is the Rasta API HTTP service.
//
// Wiring: load config -> open a pgx pool to Supabase -> build the chi router with
// the middleware chain -> serve with graceful shutdown.
//
// @title           Khoj API
// @version         1.0
// @description     A provenance-first cultural data API for India: 4,900+ creator-verified places and living traditions where every claim cites its source. Each entity carries a trust signal (how well-corroborated) and, where applicable, a freshness signal (how current). Supports geo (near/bbox) and fuzzy search.
// @BasePath        /
// (no @schemes — Swagger UI then uses the page's own protocol, so "Try it out"
//
//	calls https on Render and http locally, avoiding mixed-content failures.)
package main

import (
	"context"
	"errors"
	"log"
	"net/http"
	"net/url"
	"os"
	"os/signal"
	"strconv"
	"strings"
	"syscall"
	"time"

	"github.com/go-chi/chi/v5"
	"github.com/go-chi/chi/v5/middleware"
	"github.com/go-chi/cors"
	"github.com/jackc/pgx/v5/pgxpool"
	httpSwagger "github.com/swaggo/http-swagger"

	"github.com/keshav-const/rasta-api/internal/config"
	"github.com/keshav-const/rasta-api/internal/httpx"
	"github.com/keshav-const/rasta-api/internal/store"

	_ "github.com/keshav-const/rasta-api/docs" // generated OpenAPI spec (swag init)
)

// api holds the shared dependencies every handler needs. Handlers are methods on
// it, so swaggo can attach @annotations to them (anonymous closures can't be).
type api struct {
	db   *store.Store
	pool *pgxpool.Pool
}

func main() {
	cfg := config.Load()
	if cfg.DatabaseURL == "" {
		log.Fatal("DATABASE_URL is not set")
	}

	// pgxpool manages a pool of short-lived connections and reconnects as needed —
	// exactly what the Supabase session pooler wants (never hold one across a call).
	ctx := context.Background()
	pool, err := pgxpool.New(ctx, cfg.DatabaseURL)
	if err != nil {
		log.Fatalf("db pool: %v", err)
	}
	defer pool.Close()
	if err := pool.Ping(ctx); err != nil {
		log.Fatalf("db ping: %v", err)
	}
	a := &api{db: store.New(pool), pool: pool}

	// The middleware chain every request flows through.
	r := chi.NewRouter()
	r.Use(middleware.RequestID)
	r.Use(middleware.RealIP)
	r.Use(middleware.Logger)
	r.Use(middleware.Recoverer)
	r.Use(middleware.Timeout(15 * time.Second))
	// CORS: this is a public read API, so allow any origin to GET it (from browsers,
	// the playground, other sites). Read-only, so no credentials/writes exposed.
	r.Use(cors.Handler(cors.Options{
		AllowedOrigins: []string{"*"},
		AllowedMethods: []string{"GET", "OPTIONS"},
		AllowedHeaders: []string{"Accept", "Content-Type"},
		MaxAge:         300,
	}))

	r.Get("/healthz", a.healthz)
	// Interactive API docs (Swagger UI) served from our own binary — no external
	// service, reads the spec generated by `swag init` into ./docs.
	r.Get("/swagger/*", httpSwagger.Handler(httpSwagger.URL("/swagger/doc.json")))

	r.Route("/v1", func(r chi.Router) {
		r.Get("/stats", a.stats)
		r.Get("/places", a.listPlaces)
		r.Get("/places/{slug}", a.getPlace)
		r.Get("/cities", a.listCities)
		r.Get("/entities", a.listEntities)
	})

	srv := &http.Server{
		Addr:         ":" + cfg.Port,
		Handler:      r,
		ReadTimeout:  10 * time.Second,
		WriteTimeout: 20 * time.Second,
		IdleTimeout:  60 * time.Second,
	}

	// Serve in the background, then block until a shutdown signal.
	go func() {
		log.Printf("rasta-api listening on :%s (docs at /swagger/)", cfg.Port)
		if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
			log.Fatalf("server: %v", err)
		}
	}()

	stop := make(chan os.Signal, 1)
	signal.Notify(stop, syscall.SIGINT, syscall.SIGTERM)
	<-stop

	log.Println("shutting down...")
	shutdownCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	_ = srv.Shutdown(shutdownCtx)
}

// healthz godoc
// @Summary      Liveness & readiness
// @Description  Returns ok, and 503 if the database is unreachable.
// @Tags         system
// @Produce      json
// @Success      200 {object} httpx.Envelope
// @Failure      503 {object} httpx.Envelope
// @Router       /healthz [get]
func (a *api) healthz(w http.ResponseWriter, req *http.Request) {
	if err := a.pool.Ping(req.Context()); err != nil {
		httpx.Error(w, http.StatusServiceUnavailable, "db_unavailable", "database not reachable")
		return
	}
	httpx.JSON(w, http.StatusOK, map[string]string{"status": "ok"}, nil)
}

// stats godoc
// @Summary      Headline graph counts
// @Description  Totals for places, cities, sources and claims.
// @Tags         system
// @Produce      json
// @Success      200 {object} httpx.Envelope
// @Router       /v1/stats [get]
func (a *api) stats(w http.ResponseWriter, req *http.Request) {
	st, err := a.db.Stats(req.Context())
	if err != nil {
		log.Printf("stats: %v", err)
		httpx.Error(w, http.StatusInternalServerError, "internal", "could not load stats")
		return
	}
	httpx.JSON(w, http.StatusOK, st, nil)
}

// listPlaces godoc
// @Summary      List & filter entities
// @Description  Ranked list of places and cultural entities. Each item carries a trust object and, where applicable, a freshness object. Supports geo (near/bbox) and fuzzy search.
// @Tags         places
// @Produce      json
// @Param        city          query string  false "destination slug (e.g. jaipur)"
// @Param        country       query string  false "e.g. India"
// @Param        category      query string  false "poi_category (e.g. temple, restaurant)"
// @Param        type          query string  false "entity_type (poi, festival, sport, cuisine, ...)"
// @Param        q             query string  false "fuzzy name search (typo-tolerant, ranked)"
// @Param        min_sources   query int     false "only entities backed by >= N distinct sources"
// @Param        min_platforms query int     false "only entities across >= N distinct platforms"
// @Param        max_source_age_days query int false "drop entities whose newest source is older (enduring types exempt)"
// @Param        fresh_only    query boolean false "drop entities whose freshness would be stale (band-aware)"
// @Param        near          query string  false "lat,lng for radius search"
// @Param        radius_km     query number  false "radius (km) for near="
// @Param        bbox          query string  false "minLng,minLat,maxLng,maxLat (map viewport)"
// @Param        sort          query string  false "trust | freshness (default: recommendation score)"
// @Param        limit         query int     false "page size (<=100, default 20)"
// @Param        offset        query int     false "page offset"
// @Param        cursor        query string  false "keyset cursor from a previous response's next_cursor (default ordering only)"
// @Success      200 {object} httpx.Envelope
// @Router       /v1/places [get]
func (a *api) listPlaces(w http.ResponseWriter, req *http.Request) {
	q := req.URL.Query()
	limit := clampInt(atoiOr(q.Get("limit"), 20), 1, 100)
	offset := maxInt(atoiOr(q.Get("offset"), 0), 0)
	params := store.PlacesParams{
		City:         q.Get("city"),
		Country:      q.Get("country"),
		Category:     q.Get("category"),
		EntityType:   q.Get("type"),
		Q:            q.Get("q"),
		MinSources:   atoiOr(q.Get("min_sources"), 0),
		MinPlatforms: atoiOr(q.Get("min_platforms"), 0),
		MaxSourceAge: maxSourceAge(q),
		FreshOnly:    q.Get("fresh_only") == "true",
		Sort:         q.Get("sort"),
		Cursor:       q.Get("cursor"),
		Limit:        limit,
		Offset:       offset,
	}
	applyGeo(q, &params) // near=/radius_km=/bbox=
	places, next, err := a.db.ListPlaces(req.Context(), params)
	if err != nil {
		log.Printf("places: %v", err)
		httpx.Error(w, http.StatusInternalServerError, "internal", "could not load places")
		return
	}
	meta := map[string]any{"count": len(places), "limit": limit, "offset": offset}
	if next != "" {
		meta["next_cursor"] = next
	}
	httpx.JSON(w, http.StatusOK, places, meta)
}

// getPlace godoc
// @Summary      One place with all its sourced evidence ("receipts")
// @Description  The product's moat: returns the entity plus every source backing it (platform, title, url, creator, date), each with its stance and raw claims.
// @Tags         places
// @Produce      json
// @Param        slug path string true "entity slug"
// @Success      200 {object} httpx.Envelope
// @Failure      404 {object} httpx.Envelope
// @Router       /v1/places/{slug} [get]
func (a *api) getPlace(w http.ResponseWriter, req *http.Request) {
	slug := chi.URLParam(req, "slug")
	place, err := a.db.GetPlace(req.Context(), slug)
	if err != nil {
		log.Printf("place %q: %v", slug, err)
		httpx.Error(w, http.StatusInternalServerError, "internal", "could not load place")
		return
	}
	if place == nil {
		httpx.Error(w, http.StatusNotFound, "not_found", "no place with that slug")
		return
	}
	meta := map[string]any{"evidence_count": len(place.Evidence)}
	httpx.JSON(w, http.StatusOK, place, meta)
}

